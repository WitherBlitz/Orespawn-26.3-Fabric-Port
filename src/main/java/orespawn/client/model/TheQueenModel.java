		this.Rwing8.y = this.Rwing10.y = this.Rwing3.y;
		this.Rwing8.x = this.Rwing10.x = this.Rwing3.x;
		this.Rwing7.zRot = this.Rwing8.zRot = -0.261F + this.Rwing3.zRot;
		this.Rwing9.zRot = this.Rwing10.zRot = 0.261F + this.Rwing3.zRot;
